licenses_of() {   # the license files of the package that holds a library
    local path="$1" pkg ver
    if command -v pacman >/dev/null 2>&1 && pacman -Qoq "$path" >/dev/null 2>&1; then
        pkg="$(pacman -Qoq "$path")"; ver="$(pacman -Q "$pkg" | cut -d' ' -f2)"
        mkdir -p "$docs/licenses/$pkg"
        if [ -d "/usr/share/licenses/$pkg" ]; then cp -f /usr/share/licenses/"$pkg"/* "$docs/licenses/$pkg/" 2>/dev/null || true; fi
    elif command -v rpm >/dev/null 2>&1 && rpm -qf "$path" >/dev/null 2>&1; then
        pkg="$(rpm -qf --qf '%{NAME}' "$path")"; ver="$(rpm -qf --qf '%{VERSION}-%{RELEASE}' "$path")"
        mkdir -p "$docs/licenses/$pkg"
        rpm -qL "$pkg" | while read -r l; do [ -f "$l" ] && cp -f "$l" "$docs/licenses/$pkg/"; done
    elif command -v dpkg >/dev/null 2>&1 && dpkg -S "$path" >/dev/null 2>&1; then
        pkg="$(dpkg -S "$path" | head -1 | cut -d: -f1)"; ver="$(dpkg-query -W -f '${Version}' "$pkg")"
        mkdir -p "$docs/licenses/$pkg"
        [ -f "/usr/share/doc/$pkg/copyright" ] && cp -f "/usr/share/doc/$pkg/copyright" "$docs/licenses/$pkg/"
    elif [ "$os" = Darwin ]; then
        local keg; keg="$(cd "$(dirname "$path")/.." && pwd -P)"
        pkg="$(basename "$(dirname "$keg")")"; ver="$(basename "$keg")"
        mkdir -p "$docs/licenses/$pkg"
        find "$keg" -maxdepth 3 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' \) -exec cp -f {} "$docs/licenses/$pkg/" \;
    else
        fail "no package holds $path"
    fi
    if [ -z "$(ls -A "$docs/licenses/$pkg")" ]; then
        # A package may hold no license file (Homebrew's boost keg has none).
        # Boost's license is the Boost Software License 1.0, whose text
        # follows; for anything else a note says where the license is. A
        # missing license file never stops the build.
        case "$pkg" in
            boost*|libboost*) boost_license > "$docs/licenses/$pkg/LICENSE_1_0.txt" ;;
            *icu*) printf 'ICU is under the Unicode License (Unicode-3.0):\nhttps://github.com/unicode-org/icu/blob/main/LICENSE\n' > "$docs/licenses/$pkg/LICENSE-NOTE.txt"
                   echo "bundle-libraries.sh: WARNING no license file in $pkg; a note with the license's address written instead" >&2 ;;
            *) printf 'No license file was found in the package %s.\n' "$pkg" > "$docs/licenses/$pkg/LICENSE-NOTE.txt"
               echo "bundle-libraries.sh: WARNING no license file in $pkg" >&2 ;;
        esac
    fi
    printf '%s\t%s\n' "$pkg" "$ver"
}

if [ "$os" = Linux ]; then
    command -v patchelf >/dev/null || fail "patchelf is needed"
    needed() { readelf -d "$1" | sed -n 's/.*(NEEDED).*\[\(.*\)\]/\1/p'; }
    queue=()
    for f in "${own[@]}"; do while read -r n; do wanted "$n" && queue+=("$n"); done < <(needed "$f"); done
    seen=" "
    while [ "${#queue[@]}" -gt 0 ]; do
        n="${queue[0]}"; queue=("${queue[@]:1}")
        case "$seen" in *" $n "*) continue ;; esac
        seen="$seen$n "
        path="$(ldconfig -p | awk -v l="$n" '$1 == l {print $NF; exit}')"
        [ -n "$path" ] || fail "no system library for $n"
        real="$(realpath "$path")"
        cp "$real" "$dest/$n"
        chmod 0755 "$dest/$n"
        pv="$(licenses_of "$real")"
        printf '%s\t%s\t%s\t%s\n' "$n" "$real" "$pv" "$(sha256sum "$dest/$n" | cut -d' ' -f1)" >> "$list"
        while read -r m; do wanted "$m" && queue+=("$m"); done < <(needed "$dest/$n")
    done
    [ "$seen" != " " ] || fail "FreeLing needs no ICU or Boost library: nothing to bundle"
    # Some distributions (openSUSE) ship ICU's data as a separate file
    # (/usr/share/icu/VERSION/icudtNNl.dat) and libicudata as an empty stub,
    # so a copy of the stub alone leaves FreeLing without ICU's data ("Could
    # not initialize ICU resources") once the data package is gone. The stub
    # is then replaced by a library that holds the data itself, as ICU's own
    # build makes it (the symbol icudtNN_dat over the data file).
    for f in "$dest"/libicudata.so.*; do
        [ -f "$f" ] || continue
        [ "$(stat -c %s "$f")" -lt 1000000 ] || continue
        v="${f##*.so.}"; v="${v%%.*}"
        dat="$(ls /usr/share/icu/*/icudt"$v"l.dat 2>/dev/null | head -1 || true)"
        [ -n "$dat" ] || fail "$f is ICU's empty stub and no icudt${v}l.dat was found"
        command -v gcc >/dev/null || fail "gcc is needed to put ICU's data file into libicudata"
        tmp="$(mktemp -d)"
        printf '\t.section .rodata\n\t.globl icudt%s_dat\n\t.type icudt%s_dat, @object\n\t.balign 16\nicudt%s_dat:\n\t.incbin "%s"\n\t.size icudt%s_dat, . - icudt%s_dat\n\t.section .note.GNU-stack,"",@progbits\n' \
            "$v" "$v" "$v" "$dat" "$v" "$v" > "$tmp/data.S"
        gcc -shared -nostdlib -Wl,-soname,"$(basename "$f")" -o "$f" "$tmp/data.S"
        rm -rf "$tmp"
        pv="$(licenses_of "$(realpath "$dat")")"
        printf '%s\t%s\t%s\t%s\n' "$(basename "$f") (with ICU's data)" "$dat" "$pv" "$(sha256sum "$f" | cut -d' ' -f1)" >> "$list"
        echo "bundle-libraries.sh: $(basename "$f") holds ICU's data from $dat"
    done
    for f in "$dest"/*; do
        [ -n "$(needed "$f")" ] && patchelf --set-rpath '$ORIGIN' "$f"
    done
    for f in "${own[@]}"; do
        if [ "${RELOCATABLE:-no}" = yes ]; then
            case "$f" in
                "$prefix/bin/"*) patchelf --set-rpath '$ORIGIN/../lib/freeling-es-cl:$ORIGIN/../lib' "$f" ;;
                *)               patchelf --set-rpath '$ORIGIN/freeling-es-cl:$ORIGIN' "$f" ;;
            esac
        else
            patchelf --set-rpath "$prefix/lib/freeling-es-cl:$prefix/lib" "$f"
        fi
    done
    # Every ICU and Boost library must now come from the copies.
    for f in "${own[@]}" "$dest"/*; do
        bad="$(LD_LIBRARY_PATH= ldd "$f" | awk '$1 ~ /^lib(icu|boost_)/ {print $1, $3}' | while read -r l p; do
                   case "$(realpath -m "$p")" in "$dest"/*) ;; *) echo "$l => $p" ;; esac
               done)"
        [ -z "$bad" ] || fail "$f still loads: $bad"
    done
elif [ "$os" = Darwin ]; then
    refs() { otool -L "$1" | tail -n +2 | awk '{print $1}'; }
    search=()
    for fm in icu4c boost; do d="$(brew --prefix "$fm" 2>/dev/null)/lib"; [ -d "$d" ] && search+=("$d"); done
    resolve() {   # a reference to a real file
        local r="$1" b; b="$(basename "$r")"
        if [ -f "$r" ]; then realpath "$r"; return; fi
        for d in "${search[@]}"; do [ -f "$d/$b" ] && { realpath "$d/$b"; return; }; done
        fail "cannot find $r"
    }
    changed=("${own[@]}")
    queue=("${own[@]}")
    seen=" "
    while [ "${#queue[@]}" -gt 0 ]; do
        f="${queue[0]}"; queue=("${queue[@]:1}")
        self="$(otool -D "$f" 2>/dev/null | tail -n +2 || true)"
        while read -r r; do
            [ "$r" = "$self" ] && continue
            b="$(basename "$r")"
            wanted "$b" || continue
            case "$r" in "$dest"/*) continue ;; esac
            if case "$seen" in *" $b "*) false ;; *) true ;; esac; then
                seen="$seen$b "
                real="$(resolve "$r")"
                cp "$real" "$dest/$b"
                chmod 0755 "$dest/$b"
                install_name_tool -id "$dest/$b" "$dest/$b"
                pv="$(licenses_of "$real")"
                printf '%s\t%s\t%s\t%s\n' "$b" "$real" "$pv" "$(shasum -a 256 "$dest/$b" | cut -d' ' -f1)" >> "$list"
                queue+=("$dest/$b"); changed+=("$dest/$b")
            fi
            install_name_tool -change "$r" "$dest/$b" "$f"
        done < <(refs "$f")
    done
    [ "$seen" != " " ] || fail "FreeLing needs no ICU or Boost library: nothing to bundle"
    for f in "${changed[@]}"; do codesign --force --sign - "$f" 2>/dev/null; done
    for f in "${changed[@]}"; do
        bad="$(refs "$f" | grep -E '/lib(icu|boost_)' | grep -v "^$dest/" || true)"
        [ -z "$bad" ] || fail "$f still refers to: $bad"
    done
else
    fail "not Linux or macOS ($os): the Windows zip carries its libraries in bin/"
fi

echo "bundle-libraries.sh: $(($(wc -l < "$list") - 1)) libraries in $dest ($(du -sh "$dest" | cut -f1))"
column -t -s $'\t' "$list" 2>/dev/null || cat "$list"
