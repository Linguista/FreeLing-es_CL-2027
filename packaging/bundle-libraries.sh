#!/usr/bin/env bash
# VERSION 1.0.0
#
# bundle-libraries.sh -- copies into an installed FreeLing the ICU and Boost
# libraries its programs and libraries were built against, and makes them
# load those copies instead of the system's, so that a later upgrade of the
# system (Fedora 44 to 45, Ubuntu 24.04 to 26.04, a Homebrew upgrade of
# icu4c or boost) cannot break FreeLing. The copies go into
# PREFIX/lib/freeling-es-cl/; a list of them, with the package each came
# from, its version and its sha256, goes into
# PREFIX/share/doc/freeling-es-cl/BUNDLED-LIBRARIES.tsv, and the license
# files of those packages into PREFIX/share/doc/freeling-es-cl/licenses/.
#
# Linux: every ELF file under PREFIX/bin and PREFIX/lib gets the run path
# PREFIX/lib/freeling-es-cl:PREFIX/lib (patchelf), each copy the run path
# $ORIGIN, so the copies are found first and only by FreeLing; the folder is
# not in the system's library path. macOS: every reference to a Homebrew
# ICU or Boost library is changed to the copy's full path
# (install_name_tool), and every changed file is signed again (ad hoc).
# Every other library (the C and C++ runtimes, zlib) stays the system's.
#
# Usage: packaging/bundle-libraries.sh PREFIX
# Run it after the install and before the package is made. With
# RELOCATABLE=yes (Linux) the run paths are relative to each file
# ($ORIGIN/../lib/freeling-es-cl for the programs, $ORIGIN/freeling-es-cl
# for the libraries), so the whole prefix can be moved: the generic Linux
# tarball.

set -euo pipefail
prefix="$(cd "${1:?the install prefix}" && pwd)"
dest="$prefix/lib/freeling-es-cl"
docs="$prefix/share/doc/freeling-es-cl"
list="$docs/BUNDLED-LIBRARIES.tsv"
fail() { echo "bundle-libraries.sh: $*" >&2; exit 1; }
wanted() { case "$1" in libicu*|libboost_*) return 0 ;; *) return 1 ;; esac; }
mkdir -p "$dest" "$docs/licenses"
printf 'library\tfrom\tpackage\tversion\tsha256\n' > "$list"
os="$(uname -s)"

# The files of FreeLing itself: every program and library it installed.
own=()
while IFS= read -r f; do
    case "$os" in
        Linux)  file -b "$f" | grep -q '^ELF' && own+=("$f") ;;
        Darwin) file -b "$f" | grep -q 'Mach-O' && own+=("$f") ;;
    esac
done < <(find "$prefix/bin" "$prefix/lib" -maxdepth 1 -type f | sort)
[ "${#own[@]}" -gt 0 ] || fail "no program or library in $prefix/bin and $prefix/lib"

